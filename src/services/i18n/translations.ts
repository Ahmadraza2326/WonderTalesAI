/**
 * Returns localized string for the given key and locale, with automatic fallback to English and then to the key itself.
 */
export function t(key: keyof TranslationDictionary, locale?: SupportedLocale | string): string {
  const resolved = resolveLocaleConfig(locale || DEFAULT_LOCALE)
  const dict = TRANSLATIONS[resolved.code] || TRANSLATIONS[DEFAULT_LOCALE]
  const val = dict[key]
  if (val) return val
  return TRANSLATIONS[DEFAULT_LOCALE][key] || key
}
